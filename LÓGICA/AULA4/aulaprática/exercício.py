##Realize a sequência de print com for e while
## Inteiros de 3 até 12, com 12 incluso
## Inteiros de 0 até 9, excluindo 9, com passo de 2


for i in range(3,13,1): # cria um loop de 3 a 12
    print(i) # imprime o valor de i


i = 0 # inicializa a variável i com o valor 0

while i < 9: # enquanto i for menor que 9
    print(i) # imprime o valor de i
    i += 2 # adiciona 2 ao valor de i