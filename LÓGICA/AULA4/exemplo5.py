##Comparativo while e for

x = 1   ##Valor inicial do iterador

while x <= 10: ##Valor final do iterador
    print(x)
    x += 1 ##Passo do iterador, ou seja, o valor que será adicionado a cada iteração do loop


for x in range(1,6,1): ##1 - Valor inicial do iterador
                    ##6 - Valor final do iterador
                    ##1 - Passo do iterador
    print(x)